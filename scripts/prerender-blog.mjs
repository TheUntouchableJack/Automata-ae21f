#!/usr/bin/env node
/**
 * Prerenders published articles to real static files at blog/<slug>.html.
 *
 * Why this exists: blog/post.html is a "Loading..." shell that fetches and renders
 * the article client-side. That content is invisible to Bing and to every LLM
 * answer engine, and only reaches Google after a render-queue delay. Baking the
 * title, meta, canonical, JSON-LD, and article body into a real file fixes all of
 * that at once. It also removes the need for the /blog/:slug rewrite — Netlify's
 * extension resolution serves blog/<slug>.html for /blog/<slug> directly.
 *
 * The generated pages still load blog.js, which detects the baked content
 * (data-prerendered="1" on #post-body), skips its fetch/render path, and applies
 * only the progressive enhancements: table of contents, mid-article CTA, related
 * posts, share buttons.
 *
 * Run: node scripts/prerender-blog.mjs
 * Wired into the Netlify build command in netlify.toml.
 */

